# split() -- convert text in pieces

text = "python is a high end language"

print(text.split())

# join() -- combine string

text2 = ["python","is","easy"]
print(" ".join(text2))
 
## replace() -- modify string

text3 = "i like java"
print(text3)

text3 = text3.replace("java","python")
